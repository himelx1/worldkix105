export function getXpForNextLevel(level: number): number {
  return Math.round(100 * Math.pow(Math.max(1, level), 1.62));
}

export function getLevelCoinReward(newLevel: number): number {
  return 75 + newLevel * 50;
}

export function getBuildQueueCap(level: number): number {
  if (level >= 20) return 6;
  if (level >= 15) return 5;
  if (level >= 10) return 4;
  if (level >= 5) return 3;
  return 2;
}

