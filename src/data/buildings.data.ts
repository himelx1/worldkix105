export function getBuildingLevelMultiplier(
  level: number,
  def?: Pick<BuildingDef, 'isLargeFactory'>
): number {
  const lvl = Math.max(1, Math.floor(level));
  if (lvl === 1) return 1;
  if (def?.isLargeFactory) {
    const table = [1, 2.5, 4.5, 7.0, 10.0];
    return table[lvl - 1] ?? 10.0 + (lvl - 5) * 3.0;
  }
  return 1 + (lvl - 1) * 0.45;
}

export function getBuildingFootprint(
  def: Pick<BuildingDef, 'width' | 'height' | 'footprintRotatable'>,
  rotation: 0 | 1 = 0
): { width: number; height: number } {
  if (rotation === 1 && def.footprintRotatable !== false && def.width !== def.height) {
    return { width: def.height, height: def.width };
  }
  return { width: def.width, height: def.height };
}

export function isLargeFactory(
  def: Pick<BuildingDef, 'isLargeFactory' | 'width' | 'height'>
): boolean {
  return Boolean(def.isLargeFactory || (def.width >= 2 && def.height >= 4) || (def.width >= 4 && def.height >= 2));
}

